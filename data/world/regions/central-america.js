/**
 * Central America, 1985–89. First-level units as they stood then.
 * Nicaragua’s Caribbean coast is still the department of Zelaya
 * (the 1987 autonomy law is noted in the sources, not drawn as two regions).
 * Panama’s Canal Area is the treaty transition, not the pre-1979 Zone.
 * The Pan-American Highway stops at Yaviza. There is no Darién road.
 */

const TROPIC = { sun: 3, weather: 2 };

function region(spec) {
  return buildRegion({
    defaultBiome: "tropical",
    climate: { _default: TROPIC },
    ...spec,
  });
}

