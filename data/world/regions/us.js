function build() {
  const full = (id) => `us.${id}`;
  const neighbors = new Map();
  const add = (from, to, kind, via) => {
    if (!neighbors.has(from)) neighbors.set(from, []);
    neighbors.get(from).push({ id: full(to), kind, via, modes: kind === "sea" ? ["sea"] : kind === "trail" ? ["trail"] : kind === "rail" ? ["rail", "road"] : ["road"] });
  };
  LINKS.forEach(([a, b, kind, via]) => {
    add(a, b, kind, via);
    add(b, a, kind, via);
  });

  const territories = CITIES.map(([id, name, state, lat, lon, role, yields]) => ({
    id: full(id),
    name,
    short: name,
    country: "US",
    subdivision: state,
    lat,
    lon,
    role,
    biome: BIOME_OVERRIDE[id] || BIOME[state] || "hardwood",
    yields,
    geo: geoFromYields(yields, CLIMATE[state], role, state),
    neighbors: neighbors.get(id) || [],
    status: "occupied",
    playable: false,
    reach: "later",
    campaignId: CAMPAIGN_IDS.has(id) ? id : null,
  }));

  const byState = new Map();
  territories.forEach((t) => {
    if (t.role === "capital") byState.set(t.subdivision, t.id);
  });

  const subdivisions = SUBS.map(([id, name, kind, minLon, minLat, maxLon, maxLat]) => ({
    id,
    name,
    kind,
    country: "US",
    biome: BIOME[id] || "hardwood",
    bbox: { minLon, minLat, maxLon, maxLat },
    capital: byState.get(id),
  }));

  return {
    id: "us",
    name: "United States",
    country: "US",
    era: "1985-1989",
    status: "occupied",
    playable: false,
    reach: "later",
    bbox: COUNTRY_BBOX,
    notes: "Atlas only. Week 0 still starts in Cheyenne on the campaign board. Florida–Cuba and the Bering far shore stay on the existing sealift desks until those countries are built. Aleutian posts west of Dutch Harbor are sea-only.",
    subdivisions,
    territories,
    officers: OFFICERS.map((o) => ({ ...o, fictional: true })),
  };
}

export const US_REGION = build();
