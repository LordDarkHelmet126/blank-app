/**
 * Caribbean, 1985–89.
 * Cuba is the 1976–2010 layout: 14 provinces plus Isla de la Juventud.
 * Artemisa and Mayabeque (2011) are not here.
 * Haiti is nine departments (Nippes is 2003).
 * The Dominican Republic includes the provinces created by 1984
 * (Monseñor Nouel, Monte Plata, Hato Mayor) and not Santo Domingo
 * province or San José de Ocoa, which came later.
 * Puerto Rico and the Bahamas are major towns, not every municipio
 * or family-island district. Smaller Antilles keep their real
 * first-level units where that unit is an island, arrondissement,
 * county, or Grenada parish; parish-by-parish splits of the
 * smallest islands are a documented gap.
 */

const TROPIC = { sun: 3, weather: 1 };

function region(spec) {
  return buildRegion({
    defaultBiome: "tropical",
    climate: { _default: TROPIC },
    ...spec,
  });
}

